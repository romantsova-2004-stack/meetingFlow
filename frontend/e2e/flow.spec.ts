test('Участник добавляется по Enter без преждевременного сохранения встречи',async({page})=>{
 const people=await (await page.request.get('/api/participants')).json()
 const added={id:999999,name:'Новый участник по Enter'}
 let created=false,meetingSaved=false
 await page.route('**/api/participants',async route=>{
  if(route.request().method()==='POST'){
   created=true
   await route.fulfill({status:201,json:added})
  }else await route.fulfill({status:200,json:created?[...people,added]:people})
 })
 await page.route('**/api/meetings',async route=>{
  if(route.request().method()==='POST'){meetingSaved=true;await route.abort()}
  else await route.continue()
 })
 await page.goto('/')
 await page.getByRole('button',{name:'Создать встречу',exact:true}).first().click()
 await page.getByLabel('Тема встречи').fill('Встреча не должна сохраниться по Enter')
 await page.getByRole('textbox',{name:'Имя нового участника'}).fill(added.name)
 await page.getByRole('textbox',{name:'Имя нового участника'}).press('Enter')
 await expect(page.getByRole('checkbox',{name:new RegExp(added.name)})).toBeChecked()
 await expect(page.getByRole('dialog')).toBeVisible()
 expect(meetingSaved).toBe(false)
})
