test('При ошибке API форма остаётся открытой, ложного успеха нет',async({page})=>{
 await page.goto('/participants')
 await page.getByRole('button',{name:'Добавить участника',exact:true}).first().click()
 await page.getByLabel('Имя и фамилия').fill('Ошибка сети')
 await page.route('**/api/participants',route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({detail:'Тест: данные не сохранены'})}))
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('данные не сохранены')
 await expect(page.getByRole('dialog')).toBeVisible()
 await expect(page.getByText('Данные успешно сохранены')).toHaveCount(0)
})
