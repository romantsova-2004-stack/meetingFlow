import {test,expect} from '@playwright/test'
test('AC-01–AC-10: встреча → решение → задача → статус → контекст',async({page})=>{
 const unique=Date.now().toString(),meeting='Проверка интерфейса '+unique,person='Тестовый участник '+unique,decision='Проверить выпуск '+unique,task='Пройти полный сценарий '+unique
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Обзор рабочего пространства'})).toBeVisible()
 await page.getByRole('button',{name:'Создать встречу',exact:true}).first().click()
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByText('Введите тему встречи')).toBeVisible()
 await expect(page.getByText('Выберите минимум одного участника')).toBeVisible()
 await page.getByLabel('Тема встречи').fill(meeting)
 await page.getByRole('textbox',{name:'Имя нового участника'}).fill(person)
 await page.getByRole('button',{name:'Добавить',exact:true}).click()
 await expect(page.getByRole('checkbox',{name:new RegExp(person)})).toBeChecked()
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByRole('heading',{name:meeting,exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Редактировать',exact:true}).click()
 await expect(page.getByLabel('Тема встречи')).toHaveValue(meeting)
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByRole('dialog')).not.toBeVisible()
 await page.getByRole('button',{name:'Добавить решение',exact:true}).first().click()
 await page.getByLabel('Текст решения').fill(decision)
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByRole('heading',{name:decision,exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Создать задачу',exact:true}).click()
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByText('Выберите ответственного',{exact:true})).toBeVisible()
 await expect(page.getByText('Укажите срок выполнения',{exact:true})).toBeVisible()
 await page.getByLabel('Описание задачи').fill(task)
 await page.getByLabel('Ответственный',{exact:false}).selectOption({label:person})
 await page.getByLabel('Срок выполнения').fill('2026-10-26')
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByRole('heading',{name:task,exact:true})).toBeVisible()
 await expect(page.getByText('Просрочена',{exact:true})).toBeVisible()
 await page.getByRole('combobox',{name:'Изменить статус'}).selectOption('in_progress')
 await expect(page.getByText('Статус задачи сохранён')).toBeVisible()
 await page.getByRole('link',{name:'← Все задачи'}).click()
 await page.getByRole('button',{name:'Незавершённые',exact:true}).click()
 await page.getByRole('link',{name:task,exact:true}).click()
 await expect(page.getByRole('combobox',{name:'Изменить статус'})).toHaveValue('in_progress')
 await page.getByRole('button',{name:'Редактировать',exact:true}).click()
 await page.getByLabel('Описание задачи').fill(task+' — готово')
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByRole('heading',{name:task+' — готово',exact:true})).toBeVisible()
 await page.getByRole('combobox',{name:'Изменить статус'}).selectOption('done')
 await expect(page.getByRole('combobox',{name:'Изменить статус'})).toBeEnabled()
 await page.reload()
 await expect(page.getByRole('combobox',{name:'Изменить статус'})).toHaveValue('done')
 await expect(page.getByText('Просрочена',{exact:true})).not.toBeVisible()
 await page.getByRole('link',{name:decision,exact:false}).click()
 await expect(page.getByRole('heading',{name:meeting,exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:decision,exact:true})).toBeVisible()
 await page.getByRole('link',{name:task+' — готово',exact:true}).click()
 await page.getByRole('link',{name:'← Все задачи'}).click()
 await page.getByRole('button',{name:'Незавершённые',exact:true}).click()
 await expect(page.getByRole('link',{name:task+' — готово',exact:true})).toHaveCount(0)
})
